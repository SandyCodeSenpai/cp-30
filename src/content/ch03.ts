const TREE_ORDERS =
  "def tree_orders(n, adj, root=0):\n    parent = [-1] * n\n    order = []                      # preorder: every parent before its children\n    seen = [False] * n\n    seen[root] = True\n    stack = [root]\n    while stack:\n        u = stack.pop()\n        order.append(u)\n        for v in adj[u]:\n            if not seen[v]:\n                seen[v] = True\n                parent[v] = u\n                stack.append(v)\n    size = [1] * n\n    for u in reversed(order):       # reversed preorder: every child before its parent\n        if parent[u] != -1:\n            size[parent[u]] += size[u]\n    return parent, order, size\n";

const ENTER_EXIT =
  "def dfs_enter_exit(n, adj, root=0):\n    tin = [-1] * n\n    tout = [-1] * n\n    timer = 0\n    it = [0] * n                    # next neighbour index to try, per node\n    tin[root] = timer; timer += 1\n    stack = [root]\n    while stack:\n        u = stack[-1]\n        if it[u] < len(adj[u]):\n            v = adj[u][it[u]]\n            it[u] += 1\n            if tin[v] == -1:        # unvisited: this is the \"recursive call\"\n                tin[v] = timer; timer += 1\n                stack.append(v)\n        else:                       # all neighbours done: post-order point\n            stack.pop()\n            tout[u] = timer; timer += 1\n    return tin, tout\n";

