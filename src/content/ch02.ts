/* ---------- Daily Temperatures flip-book helpers ---------- */
const T = [73, 74, 75, 71, 69, 72, 76, 73];
const ANS = [1, 1, 4, 2, 1, 1, 0, 0];

function dt(o: {
  i?: number;
  tones?: Record<number, Tone>;
  range?: [number, number, string?];
  stack?: number[];
  ans?: (number | string)[];
  ansTones?: Record<number, Tone>;
  caption?: string;
}): Visual {
  const rows: ArrayRow[] = [{
    label: "temps",
    items: T,
    pointers: o.i === undefined ? undefined : [{ at: o.i, label: "i", tone: "accent" }],
    ranges: o.range ? [{ from: o.range[0], to: o.range[1], tone: "warn", label: o.range[2] }] : undefined,
    tones: o.tones,
  }];
  if (o.stack) rows.push({ label: "stack", items: o.stack.length ? o.stack.map((j) => `d${j}: ${T[j]}`) : ["empty"], tones: o.stack.length ? { [o.stack.length - 1]: "accent" } : undefined });
  if (o.ans) rows.push({ label: "answer", items: o.ans, tones: o.ansTones });
  return { kind: "array", rows, indices: true, caption: o.caption };
}

