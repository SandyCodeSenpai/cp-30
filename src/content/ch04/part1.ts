const PAIR_SUM = L(
  "def pair_sum(a, target):",
  "    i, j = 0, len(a) - 1",
  "    while i < j:",
  "        s = a[i] + a[j]",
  "        if s == target:",
  "            return i, j",
  "        if s < target:",
  "            i += 1",
  "        else:",
  "            j -= 1",
  "    return -1, -1",
);

const THREE_SUM = L(
  "def three_sum(nums):",
  "    nums.sort()",
  "    n, res = len(nums), []",
  "    for i in range(n - 2):",
  "        if i > 0 and nums[i] == nums[i - 1]:",
  "            continue                          # skip duplicate first value",
  "        lo, hi = i + 1, n - 1",
  "        while lo < hi:",
  "            s = nums[i] + nums[lo] + nums[hi]",
  "            if s < 0:",
  "                lo += 1",
  "            elif s > 0:",
  "                hi -= 1",
  "            else:",
  "                res.append([nums[i], nums[lo], nums[hi]])",
  "                lo += 1",
  "                hi -= 1",
  "                while lo < hi and nums[lo] == nums[lo - 1]:",
  "                    lo += 1                   # skip duplicate second value",
  "    return res",
);

