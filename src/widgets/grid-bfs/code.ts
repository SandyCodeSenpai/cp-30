export const BFS_CODE = [
  "from collections import deque",
  "",
  "DIRS = ((1, 0), (-1, 0), (0, 1), (0, -1))",
  "",
  "# Grid BFS. One source = single-source BFS. Many sources = multi-source BFS.",
  "def grid_bfs(grid, sources, wall='#'):",
  "    R, C = len(grid), len(grid[0])",
  "    dist = [[-1] * C for _ in range(R)]",
  "    q = deque()",
  "    for r, c in sources:",
  "        dist[r][c] = 0",
  "        q.append((r, c))",
  "    while q:",
  "        r, c = q.popleft()",
  "        for dr, dc in DIRS:",
  "            nr, nc = r + dr, c + dc",
  "            if 0 <= nr < R and 0 <= nc < C and dist[nr][nc] == -1 and grid[nr][nc] != wall:",
  "                dist[nr][nc] = dist[r][c] + 1      # mark on PUSH",
  "                q.append((nr, nc))",
  "    return dist                                     # -1 = unreachable",
];

export const DFS_CODE = [
  "# Connected components on an adjacency list, iterative DFS",
  "def count_components(n, adj):",
  "    seen = [False] * n",
  "    comps = 0",
  "    for s in range(n):",
  "        if seen[s]:",
  "            continue",
  "        comps += 1",
  "        seen[s] = True",
  "        stack = [s]",
  "        while stack:",
  "            u = stack.pop()",
  "            for v in adj[u]:",
  "                if not seen[v]:",
  "                    seen[v] = True",
  "                    stack.append(v)",
  "    return comps",
];

export const ZERO_ONE_CODE = [
  "from collections import deque",
  "",
  "# 0-1 BFS on a grid. cost(r, c, nr, nc) returns 0 or 1.",
  "def zero_one_bfs(R, C, start, cost):",
  "    INF = float('inf')",
  "    dist = [[INF] * C for _ in range(R)]",
  "    sr, sc = start",
  "    dist[sr][sc] = 0",
  "    dq = deque([(sr, sc)])",
  "    while dq:",
  "        r, c = dq.popleft()",
  "        for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):",
  "            nr, nc = r + dr, c + dc",
  "            if 0 <= nr < R and 0 <= nc < C:",
  "                w = cost(r, c, nr, nc)",
  "                nd = dist[r][c] + w",
  "                if nd < dist[nr][nc]:",
  "                    dist[nr][nc] = nd",
  "                    if w == 0:",
  "                        dq.appendleft((nr, nc))   # same distance: front",
  "                    else:",
  "                        dq.append((nr, nc))       # one more: back",
  "    return dist",
];
